/// <reference lib="dom" />
import {test,expect} from '@playwright/test';
test.beforeEach(async({page})=>{await page.addInitScript(()=>localStorage.setItem('biotwin-tour-v1','dismissed'));});

test('database patient, longitudinal check-ins, goals, appointments and exports feed the existing twin',async({page})=>{
  const name='Synthetic database QA '+Date.now();
  await page.goto('/');await page.getByRole('button',{name:'Patient records',exact:true}).click();
  await page.getByRole('button',{name:'New database patient'}).click();
  const modal=page.getByRole('dialog');await modal.getByLabel('Patient name / alias').fill(name);
  await modal.getByRole('button',{name:'Save patient record',exact:true}).click();
  await expect(page.getByRole('heading',{name,exact:true})).toBeVisible();
  await page.getByRole('button',{name:'check in',exact:true}).click();
  await page.getByLabel('Weight (kg)',{exact:true}).fill('100');
  await page.getByLabel('Height (cm)',{exact:true}).fill('165');
  await page.getByLabel('Glucose (mmol/L)',{exact:true}).fill('8');
  await page.getByLabel('Systolic BP (mmHg)',{exact:true}).fill('130');
  await page.getByLabel('Diastolic BP (mmHg)',{exact:true}).fill('80');
  await page.getByLabel('Sleep (h/night)',{exact:true}).fill('7');
  await page.getByLabel('Weekly activity (min/week)',{exact:true}).fill('210');
  await page.getByRole('button',{name:'Save health check-in'}).click();
  await expect(page.getByRole('status').filter({hasText:'Saved to the local database.'})).toBeVisible();
  await page.getByRole('button',{name:'history',exact:true}).click();
  await expect(page.locator('.clinic-ui .record-table')).toContainText('100 kg');
  await expect(page.locator('.clinic-ui .record-table')).toContainText('8 mmol/L');
  await page.getByRole('button',{name:'goals',exact:true}).click();
  await page.getByLabel('Target value (kg)',{exact:true}).fill('90');
  await page.getByLabel('Target date',{exact:true}).fill('2027-01-01');
  await page.getByRole('button',{name:'Save measurement goal'}).click();
  await expect(page.locator('.clinic-ui .record-card')).toContainText('Baseline 100');
  await page.getByRole('button',{name:'appointments',exact:true}).click();
  await page.getByLabel('Clinician / team',{exact:true}).fill('Demo team');
  await page.getByLabel('Appointment date and time',{exact:true}).fill('2026-12-01T10:00');
  await page.getByRole('button',{name:'Request local appointment'}).click();
  await page.getByRole('button',{name:'confirmed',exact:true}).click();
  await expect(page.locator('.clinic-ui .record-card')).toContainText('confirmed');
  await page.getByRole('button',{name:'export',exact:true}).click();
  const event=page.waitForEvent('download');await page.getByRole('button',{name:'Complete record JSON'}).click();
  const stream=await(await event).createReadStream();const parts:Buffer[]=[];for await(const chunk of stream!)parts.push(Buffer.from(chunk));const json=JSON.parse(Buffer.concat(parts).toString());
  expect(json.profile.displayName).toBe(name);expect(json.observations[0].weightKg).toBe(100);expect(json.appointments[0].status).toBe('confirmed');expect(json.goals[0].targetValue).toBe(90);expect(Array.isArray(json.forecast.outcomes)).toBe(true);
  await page.emulateMedia({media:'print'});await expect(page.locator('.clinic-record-print')).toContainText(name);await expect(page.locator('.clinic-record-print')).toContainText('100 kg');await page.emulateMedia({media:'screen'});
  await page.reload();await page.getByRole('button',{name:'Patient records',exact:true}).click();
  await page.getByLabel('Find patient',{exact:true}).fill(name);await page.locator('.record-patient',{hasText:name}).click();
  await page.getByRole('button',{name:'Open twin from latest measurements'}).click();
  await expect(page.locator('.twin-viewport')).toHaveAttribute('data-weight-kg','100');
  await expect(page.locator('.canvas-wrap')).toHaveAttribute('data-stage','ready',{timeout:45000});
  await expect(page.getByRole('button',{name:'Disease in 3D',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Compare A / B',exact:true}).click();
  await page.getByRole('button',{name:'Create matched twin',exact:true}).click();
  await page.getByRole('button',{name:'Configure B',exact:true}).click();
  await page.getByRole('button',{name:'Confirm and apply'}).click();
  await page.getByRole('button',{name:'Run comparison · +5 min'}).click();
  await expect(page.locator('.branch-pair')).toContainText('05:05');
  await page.getByRole('button',{name:'Save twin to database',exact:true}).click();
  await expect(page.getByRole('status').filter({hasText:'Twin session saved in the SQLite database.'})).toBeVisible();
  await page.reload();
  await page.getByRole('button',{name:'Patient records',exact:true}).click();
  await page.getByLabel('Find patient',{exact:true}).fill(name);
  await page.locator('.record-patient',{hasText:name}).click();
  await page.getByRole('button',{name:'sessions',exact:true}).click();
  await page.getByRole('button',{name:'Restore saved twin'}).first().click();
  await expect(page.locator('.transport-clock')).toContainText('05:05');
  await expect(page.locator('.twin-viewport')).toHaveCount(2);
});

test('patient records works on a narrow screen and reports API failures clearly',async({page})=>{
  await page.setViewportSize({width:390,height:844});await page.goto('/');
  await page.route('**/api/records/patients',route=>route.fulfill({status:503,contentType:'application/json',body:'{"ok":false,"error":"Database temporarily unavailable"}'}));
  await page.getByRole('button',{name:'Patient records',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('Database temporarily unavailable');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
});
